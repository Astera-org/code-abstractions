"""Write the program-call process config: N languages x F function generators, plus optional extra
components (for the fine-tuning transfer experiment: the new function in ONE language, upweighted).

    uv run python programming_minimal_model/toy/gen_program_config.py --n-langs 8
    uv run python programming_minimal_model/toy/gen_program_config.py --n-langs 8 \
        --functions mess3,no_repeat,sum_mod3,diff_mod3            # 32 components, the transfer reference
    uv run python programming_minimal_model/toy/gen_program_config.py --n-langs 8 \
        --extra diff_mod3:0:8:0.8 --name nonergodic_24x_program_call_ft_diff_easy
    uv run python programming_minimal_model/toy/gen_program_config.py --n-langs 8 \
        --extra diff_mod3:0:8:0.0 --name nonergodic_24x_program_call_ft_diff_hard

--extra GEN:LANG:WEIGHT:Q_SHARED appends one component (generator GEN rendered in language LANG with
its own shared-rendering probability Q_SHARED) with mixture weight WEIGHT relative to 1 for each base
component. Extra components come after all base components, so the base grid stays language-major.

Writes training/configs/generative_process/<name>.yaml (default nonergodic_{F*N}x_program_call). The
YAML is written out in full (OmegaConf cannot load anchors/aliases), so regenerate rather than edit.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "training"))

from matrices import program_call_initial_state

# Function generators and their parameters; the default component order is f = 0, 1, 2.
FUNCTION_LIBRARY: dict[str, dict[str, float]] = {
    "mess3": {"x": 0.15, "a": 0.6},
    "no_repeat": {"rho": 0.05},
    "sum_mod3": {"delta": 0.1},
    "diff_mod3": {"delta": 0.1},
}
DEFAULT_FUNCTIONS = ["mess3", "no_repeat", "sum_mod3"]
# Shared by every component: the watcher, the return hazards, the language machine.
SHARED: dict[str, object] = {
    "pattern": [0, 1],
    "p_fire": 0.9,
    "p_floor": 0.01,
    "q_shared": 0.8,
    "p_content_to_filler": 1.0 / 24.0,
    "p_filler_to_content": 1.0 / 8.0,
}
N_LOCAL = 9  # S:0 S:1 S:2 S:F L:0 L:1 L:2 L:F B


def _yaml_inline(d: dict[str, object]) -> str:
    parts = []
    for k, v in d.items():
        if isinstance(v, list):
            parts.append(f"{k}: [{', '.join(str(x) for x in v)}]")
        elif isinstance(v, str):
            parts.append(f"{k}: {v}")
        else:
            parts.append(f"{k}: {v!r}")
    return "{" + ", ".join(parts) + "}"


def vocab_map(lang: int, n_langs: int) -> list[int]:
    """Local [S:0..2, S:F, L:0..2, L:F, B] -> global [0..3, 4+4l..7+4l, 4+4N]."""
    return [0, 1, 2, 3, *[4 + 4 * lang + k for k in range(4)], 4 + 4 * n_langs]


def render(n_langs: int, functions: list[str], extras: list[tuple[str, int, float, float]], name: str,
           base_weight: float = 1.0, base_langs: list[int] | None = None) -> str:
    n_f = len(functions)
    n_base = n_f * n_langs
    n_comp = n_base + len(extras)
    n_tokens = 4 + 4 * n_langs + 1
    lines = [
        f"# Program toy, second design: {n_langs} languages x {n_f} function generators"
        + (f" + {len(extras)} extra component(s)." if extras else "."),
        f"# Base component c = {n_f} * language + function; functions in order: {', '.join(functions)}",
        "# (see `program_call` in training/matrices.py). Every component is the same construction:",
        "# a two-mode language machine (content / filler) gating a function machine (generator + shared",
        "# '01' watcher + soft return). The language enters only through vocab_maps: shared tokens",
        f"# S:k -> k, S:F -> 3, language tokens L_l:k -> 4 + 4l + k, L_l:F -> 7 + 4l, blank -> {4 + 4 * n_langs}.",
        f"# {n_tokens} tokens; BOS is appended on top (d_vocab {n_tokens + 1}).",
    ]
    for gen, lang, weight, q in extras:
        lines.append(f"# extra component: {gen} in language {lang} only, weight {weight} (base components {base_weight}), q_shared {q}.")
    lines += [
        "#",
        "# Generated by programming_minimal_model/toy/gen_program_config.py -- regenerate, don't edit.",
        f"name: {name}",
        "instance:",
        "  _target_: genproc.generative_processes.nonergodic_generative_process.NonErgodicGenerativeProcess",
        "  _convert_: all",
        "  components:",
    ]

    def component(gen: str, shared: dict[str, object]) -> list[str]:
        params = FUNCTION_LIBRARY[gen]
        pp = {"generator": gen, **params, **shared}
        init = program_call_initial_state(gen, **params, pattern=tuple(shared["pattern"]))  # type: ignore[arg-type]
        return [
            "    - _target_: genproc.generative_processes.builder.build_hidden_markov_model",
            "      process_name: program_call",
            f"      process_params: {_yaml_inline(pp)}",
            f"      initial_state: [{', '.join(repr(v) for v in init)}]",
            "      device: ${device}",
        ]

    for lang in range(n_langs):
        lines.append(f"    # language {lang}")
        for gen in functions:
            lines += component(gen, SHARED)
    for gen, lang, weight, q in extras:
        lines.append(f"    # extra: {gen} in language {lang}")
        lines += component(gen, {**SHARED, "q_shared": q})
    weights = [repr(float(base_weight) if (base_langs is None or lang in base_langs) else 0.0)
               for lang in range(n_langs) for _ in functions] + [repr(float(w)) for _, _, w, _ in extras]
    lines.append(f"  component_weights: [{', '.join(weights)}]")
    lines.append("  # local [S:0, S:1, S:2, S:F, L:0, L:1, L:2, L:F, B] -> global")
    lines.append("  vocab_maps:")
    for lang in range(n_langs):
        vm = vocab_map(lang, n_langs)
        for f in range(n_f):
            tag = f"      # language {lang}" if f == 0 else ""
            lines.append(f"    - [{', '.join(str(v) for v in vm)}]{tag}")
    for gen, lang, _, _ in extras:
        vm = vocab_map(lang, n_langs)
        lines.append(f"    - [{', '.join(str(v) for v in vm)}]      # extra: {gen} in language {lang}")
    lines += [
        "  device: ${device}",
        "",
        "base_vocab_size: ???",
        "bos_token: ???",
        "eos_token: null",
        "vocab_size: ???",
        "",
    ]
    assert n_comp == n_base + len(extras)
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-langs", type=int, required=True)
    ap.add_argument("--functions", default=",".join(DEFAULT_FUNCTIONS))
    ap.add_argument("--extra", action="append", default=[], help="GEN:LANG:WEIGHT:Q_SHARED, repeatable")
    ap.add_argument("--name", default=None)
    ap.add_argument("--base-weight", type=float, default=1.0, help="mixture weight of every base component (0 = never sampled; keeps the vocabulary)")
    ap.add_argument("--base-langs", default=None, help="comma-separated languages whose base components get --base-weight; all other languages get 0")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    functions = args.functions.split(",")
    extras = []
    for e in args.extra:
        gen, lang, weight, q = e.split(":")
        extras.append((gen, int(lang), float(weight), float(q)))
    name = args.name or f"nonergodic_{len(functions) * args.n_langs}x_program_call"
    out = args.out or REPO / "training" / "configs" / "generative_process" / f"{name}.yaml"
    base_langs = [int(v) for v in args.base_langs.split(",")] if args.base_langs else None
    out.write_text(render(args.n_langs, functions, extras, name, args.base_weight, base_langs))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
